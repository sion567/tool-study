    public static void main(String[] args) {
        long key = Long.parseUnsignedLong("133457799BBCDFF1", 16);    //@DATA 密钥（经典例）
        long plain = Long.parseUnsignedLong("0123456789ABCDEF", 16);  // 明文（64 位块）
        int[][] rk = expandKey(key);                    // 16 把子密钥：PC1 选 56 位 → 循环左移 → PC2 选 48 位
        int[] x = permute(toBits(plain), IP);           // 初始置换 IP：64 位重排，历史包袱（硬件并线时代产物）
        int[] l = java.util.Arrays.copyOfRange(x, 0, 32);    // L0 = IP 后前 32 位
        int[] r = java.util.Arrays.copyOfRange(x, 32, 64);   // R0 = IP 后后 32 位
        for (int i = 1; i <= 16; i++) {                 // 16 轮 Feistel：L(i)=R(i-1)、R(i)=L(i-1)⊕f
            int[] f = feistel(r, rk[i]);                // f = P(S(E(R)⊕K))：扩展→加钥→S 盒→置换
            int[] nl = r.clone();
            for (int b = 0; b < 32; b++) r[b] = l[b] ^ f[b];
            l = nl;                                     // 左右免费交换——f 不要求可逆
        }
        int[] pre = new int[64];                        // 16 轮后左右交换：pre = R16||L16
        System.arraycopy(r, 0, pre, 0, 32);
        System.arraycopy(l, 0, pre, 32, 32);
        System.out.println("密文 = " + bitsHex(permute(pre, FP)));   // 逆置换 IP⁻¹ 收尾
        // 经典例命中 85e813540f0ab405；解密 = 子密钥倒序重放同一轮函数（加密器就是解密器）
    }

    // ---- 轮函数 f：E 扩展 32→48 → ⊕K → S1-S8 六进四出 → P 置换 ----
    static int[] feistel(int[] r, int[] k) {
        int[] e = permute(r, E);
        for (int i = 0; i < 48; i++) e[i] ^= k[i];      // 48 位与子密钥对撞
        int[] s = new int[32];
        for (int b = 0; b < 8; b++) {                   // 8 个 S 盒并行：首末位定行、中间 4 位定列
            int row = e[b * 6] * 2 + e[b * 6 + 5];
            int col = e[b * 6 + 1] * 8 + e[b * 6 + 2] * 4 + e[b * 6 + 3] * 2 + e[b * 6 + 4];
            int v = SBOX[b * 4 + row][col];             // SBOX：32 行 = 8 盒 × 4 行
            for (int j = 0; j < 4; j++) s[b * 4 + j] = (v >>> (3 - j)) & 1;
        }
        return permute(s, P);
    }

    // ---- 密钥扩展：64 位 → PC1 奔 56 位（每字节第 8 位是奇偶校验，弃）→ 移位 → PC2 奔 48 位 ----
    static int[][] expandKey(long key) {
        int[] cd = permute(toBits(key), PC1);           // C‖D 各 28 位
        int[][] rk = new int[17][48];
        for (int i = 1; i <= 16; i++) {
            for (int s = 0; s < SHIFTS[i - 1]; s++) {   // 每轮循环左移 1/2 位
                int t = cd[0];
                System.arraycopy(cd, 1, cd, 0, 27); cd[27] = t;
                t = cd[28];
                System.arraycopy(cd, 29, cd, 28, 27); cd[55] = t;
            }
            rk[i] = permute(cd, PC2);
        }
        return rk;
    }

    static int[] permute(int[] b, int[] p) {            // 通用置换：out[i] = b[p[i]-1]（表是 1-based 位号）
        int[] out = new int[p.length];
        for (int i = 0; i < p.length; i++) out[i] = b[p[i] - 1];
        return out;
    }

    static int[] toBits(long v) {
        int[] b = new int[64];
        for (int i = 0; i < 64; i++) b[i] = (int) ((v >>> (63 - i)) & 1);
        return b;
    }

    static String bitsHex(int[] b) {
        long v = 0;
        for (int i = 0; i < 64; i++) v = (v << 1) | b[i];
        return String.format("%016x", v);
    }

